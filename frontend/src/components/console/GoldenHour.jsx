import React, { useEffect, useRef, useState } from 'react';
import { useToast } from '../../services/toast.jsx';

const DURATION_S = 2 * 60 * 60; // 2 hours
const STORAGE_KEY = 'cybershild_golden_hour_start';

const STEPS = [
  { title: '1. Block & freeze', body: 'Call your bank\'s official helpline (the number on your card, not one from the scam message) and block the card/account or freeze UPI immediately.' },
  { title: '2. Call 1930', body: 'Dial the National Cybercrime Helpline 1930 right away - acting within the first hour gives banks the best chance to freeze the beneficiary account before funds move on.' },
  { title: '3. File online', body: 'File a complaint at cybercrime.gov.in with the transaction details, screenshots, and the message/number involved.' },
  { title: '4. Dispute with your bank', body: 'Submit a written fraud dispute to your bank within 3 working days of noticing the transaction (see the draft below).' },
];

function formatTime(totalSeconds) {
  const h = String(Math.floor(totalSeconds / 3600)).padStart(2, '0');
  const m = String(Math.floor((totalSeconds % 3600) / 60)).padStart(2, '0');
  const s = String(Math.floor(totalSeconds % 60)).padStart(2, '0');
  return `${h}:${m}:${s}`;
}

/** Builds a real complaint draft from the actual last scan result, if any. */
function buildComplaintDraft(lastResult, lastInput) {
  const now = new Date().toLocaleString();
  const categories = lastResult?.detectedThreats?.length ? lastResult.detectedThreats.join(', ') : 'Unspecified suspicious activity';
  const reasons = lastResult?.reasons?.length ? lastResult.reasons.map((r) => `   - ${r}`).join('\n') : '   - (No prior CyberShild scan attached - describe the incident manually.)';

  return `================================================================================
CYBER FRAUD INCIDENT REPORT DRAFT
For: National Cyber Crime Reporting Portal (1930 / cybercrime.gov.in)
Generated by: CyberShild
================================================================================

1. INCIDENT METADATA
   - Generated on: ${now}
   - Assessed risk level: ${lastResult?.riskLevel || 'N/A'} (score: ${lastResult?.riskScore ?? 'N/A'}/100)
   - Identified category: ${categories}

2. MESSAGE / LINK / ID IN QUESTION
--------------------------------------------------------------------------------
${lastInput ? lastInput.replace(/"/g, "'") : '(paste the exact message, link, or UPI ID here)'}
--------------------------------------------------------------------------------

3. WHY THIS WAS FLAGGED
${reasons}

4. IMMEDIATE ACTIONS TAKEN
   - [ ] Blocked card / froze account
   - [ ] Called 1930
   - [ ] Filed report at cybercrime.gov.in
   - [ ] Submitted written dispute to bank

================================================================================`;
}

export default function GoldenHour({ lastResult, lastInput }) {
  const { showToast } = useToast();
  const [running, setRunning] = useState(false);
  const [remaining, setRemaining] = useState(DURATION_S);
  const intervalRef = useRef(null);

  useEffect(() => {
    const startedAt = localStorage.getItem(STORAGE_KEY);
    if (startedAt) {
      const elapsed = Math.floor((Date.now() - Number(startedAt)) / 1000);
      if (elapsed < DURATION_S) {
        setRunning(true);
        setRemaining(DURATION_S - elapsed);
      } else {
        localStorage.removeItem(STORAGE_KEY);
      }
    }
  }, []);

  useEffect(() => {
    if (!running) return undefined;
    intervalRef.current = setInterval(() => {
      setRemaining((r) => {
        if (r <= 1) {
          clearInterval(intervalRef.current);
          setRunning(false);
          localStorage.removeItem(STORAGE_KEY);
          return 0;
        }
        return r - 1;
      });
    }, 1000);
    return () => clearInterval(intervalRef.current);
  }, [running]);

  function start() {
    localStorage.setItem(STORAGE_KEY, String(Date.now()));
    setRemaining(DURATION_S);
    setRunning(true);
  }

  function reset() {
    localStorage.removeItem(STORAGE_KEY);
    setRunning(false);
    setRemaining(DURATION_S);
  }

  async function copyDraft() {
    const draft = buildComplaintDraft(lastResult, lastInput);
    try {
      await navigator.clipboard.writeText(draft);
      showToast('Complaint draft copied to clipboard.', 'success');
    } catch {
      showToast('Could not copy automatically - select and copy the text manually.', 'error');
    }
  }

  return (
    <div className="golden-hour">
      <div className="card glass-card golden-timer-card">
        <h3 style={{ marginTop: 0 }}>Golden Hour Timer</h3>
        <p className="muted">If money has already been sent, acting in the first hour gives banks the best chance to freeze it before it moves on.</p>
        <div className="golden-timer">{formatTime(remaining)}</div>
        <div className="analyze-actions">
          {!running ? (
            <button type="button" className="btn" onClick={start}>Start timer</button>
          ) : (
            <button type="button" className="btn-outline" onClick={reset}>Reset</button>
          )}
        </div>
      </div>

      <div className="card glass-card">
        <h3 style={{ marginTop: 0 }}>What to do, in order</h3>
        <ol className="golden-steps">
          {STEPS.map((s) => (
            <li key={s.title}>
              <strong>{s.title}</strong>
              <p className="muted">{s.body}</p>
            </li>
          ))}
        </ol>
      </div>

      <div className="card glass-card">
        <h3 style={{ marginTop: 0 }}>Complaint draft</h3>
        <p className="muted">
          {lastResult ? 'Built from your most recent scan on this page.' : 'Run a check in the Scanner tab first to auto-fill this with real details.'}
        </p>
        <pre className="complaint-draft">{buildComplaintDraft(lastResult, lastInput)}</pre>
        <button type="button" className="btn" onClick={copyDraft}>Copy draft</button>
      </div>
    </div>
  );
}
